/**
 * Tier 5 Adversarial Test Suite: End-to-End Integrated Dataflow Pipeline
 * Authoritative source: ORIGINAL_REQUEST.md §R4, R5 & PROJECT.md
 * 
 * Verifies:
 * 1. Automator Slot Generation -> Guardrail Pre-Flight -> Render Conformance -> Publisher Dry-Run
 * 2. Adversarial Tamper Injection at every stage of the dataflow
 * 3. Schema integrity across Reel and Carousel configurations
 * 4. Zero live mutation leakage during pipeline execution
 * 5. Network boundary resilience (graceful handling of public tunnel rate limiting)
 */

const { test, describe } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.resolve(__dirname, '../..');
const automator = require(path.join(PROJECT_ROOT, 'scripts/lira_content_automator.js'));
const guardrails = require(path.join(PROJECT_ROOT, 'scripts/validate_guardrails.js'));
const publisher = require(path.join(PROJECT_ROOT, 'scripts/publish_now.js'));
const carouselVerifier = require(path.join(PROJECT_ROOT, 'scripts/verify_carousel_render.js'));
const { probeMedia } = require('../helpers/media_verifier');
const { REEL_SPECS, CAROUSEL_SPECS } = require('../helpers/test_constants');

describe('Tier 5 Adversarial: End-to-End Integrated Dataflow Pipeline', () => {

  // =========================================================================
  // 1. Automator -> Guardrails Validation Pass
  // =========================================================================
  describe('1. Automator -> Guardrails Validation Pass', () => {
    test('All 10 production blueprints generated by automator pass guardrail validation with 0 violations', () => {
      const blueprints = automator.PRODUCTION_SLOT_BLUEPRINTS;
      assert.strictEqual(blueprints.length, 10, 'Must have exactly 10 production blueprints');

      for (let i = 0; i < blueprints.length; i++) {
        const bp = blueprints[i];
        assert.doesNotThrow(
          () => guardrails.validateContent(bp),
          `Blueprint ${bp.id} failed guardrail validation`
        );
        const result = guardrails.checkContentSafe(bp);
        assert.strictEqual(result.valid, true, `Blueprint ${bp.id} should be valid`);
        assert.strictEqual(result.violations.length, 0, `Blueprint ${bp.id} had violations`);
      }
    });

    test('Adversarial Tampering: Corrupting any field of an automator slot triggers GuardrailError', () => {
      const baseReel = { ...automator.PRODUCTION_SLOT_BLUEPRINTS[0] };
      const baseCarousel = { ...automator.PRODUCTION_SLOT_BLUEPRINTS[1] };

      // Corrupt verbal_hook with exact bottle count
      const tamperedVerbal = { ...baseReel, verbal_hook: 'Tersedia cuma 42 botol saja!' };
      assert.throws(
        () => guardrails.validateContent(tamperedVerbal),
        (err) => err instanceof guardrails.GuardrailError && err.violations.some(v => v.rule === 'NUMERIC_SCARCITY')
      );

      // Corrupt written_hook with school leak
      const tamperedWritten = { ...baseReel, written_hook: 'RESEP DARI UPH COLLEGE' };
      assert.throws(
        () => guardrails.validateContent(tamperedWritten),
        (err) => err instanceof guardrails.GuardrailError && err.violations.some(v => v.rule === 'PRIVATE_SCHOOL_NAME')
      );

      // Corrupt topic with financial leak
      const tamperedTopic = { ...baseReel, topic: 'Bocoran HPP dan margin 74% Lira' };
      assert.throws(
        () => guardrails.validateContent(tamperedTopic),
        (err) => err instanceof guardrails.GuardrailError && err.violations.some(v => v.rule === 'FINANCIAL_LEAK')
      );

      // Corrupt caption with ceremonial matcha
      const tamperedCaption = { ...baseReel, caption: 'Pakai ceremonial matcha impor. Order via bio.' };
      assert.throws(
        () => guardrails.validateContent(tamperedCaption),
        (err) => err instanceof guardrails.GuardrailError && err.violations.some(v => v.rule === 'BANNED_TERMS')
      );

      // Corrupt caption with emoji
      const tamperedEmoji = { ...baseReel, caption: 'Matcha nikmat 🍵 siap antar!' };
      assert.throws(
        () => guardrails.validateContent(tamperedEmoji),
        (err) => err instanceof guardrails.GuardrailError && err.violations.some(v => v.rule === 'EMOJI_DETECTED')
      );

      // Corrupt carousel slide body with stevia dosage
      const tamperedSlide = JSON.parse(JSON.stringify(baseCarousel));
      tamperedSlide.slides[2].body = 'Gunakan tepat 2 tetes stevia per sajian';
      assert.throws(
        () => guardrails.validateContent(tamperedSlide),
        (err) => err instanceof guardrails.GuardrailError && err.violations.some(v => v.rule === 'EXACT_STEVIA_DOSAGE')
      );
    });
  });

  // =========================================================================
  // 2. Guardrails -> Render Verification Pass
  // =========================================================================
  describe('2. Guardrails -> Render Verification Conformance', () => {
    test('Reel media asset conforms to Remotion 9:16 rendering specifications', () => {
      const sampleReelPath = path.join(PROJECT_ROOT, 'out/sample_reel_1080x1920.mp4');
      assert.ok(fs.existsSync(sampleReelPath), `Rendered sample reel must exist at ${sampleReelPath}`);

      const meta = probeMedia(sampleReelPath);
      assert.strictEqual(meta.width, REEL_SPECS.WIDTH, 'Reel width must be 1080');
      assert.strictEqual(meta.height, REEL_SPECS.HEIGHT, 'Reel height must be 1920');
      assert.strictEqual(meta.fps, REEL_SPECS.FPS, 'Reel FPS must be 30');
      assert.strictEqual(meta.videoCodec, 'h264', 'Video codec must be h264');
      assert.strictEqual(meta.audioCodec, 'aac', 'Audio codec must be aac');
      assert.ok(meta.duration >= REEL_SPECS.MIN_DURATION_SEC && meta.duration <= REEL_SPECS.MAX_DURATION_SEC,
        `Duration ${meta.duration}s must be between 22s and 35s`);
    });

    test('Carousel media assets conform to 4:5 editorial specifications', () => {
      const sampleCarouselDir = path.join(PROJECT_ROOT, 'out/sample_carousel');
      assert.ok(fs.existsSync(sampleCarouselDir), `Carousel directory must exist at ${sampleCarouselDir}`);

      const files = fs.readdirSync(sampleCarouselDir).filter(f => /^slide\d+\.jpe?g$/i.test(f));
      assert.ok(files.length >= CAROUSEL_SPECS.MIN_SLIDES && files.length <= CAROUSEL_SPECS.MAX_SLIDES,
        `Slide count ${files.length} must be between 6 and 8`);

      // Run programmatic verification from verify_carousel_render.js
      const passed = carouselVerifier.runVerification();
      assert.strictEqual(passed, true, 'Carousel verification suite must pass all 21 checks');
    });
  });

  // =========================================================================
  // 3. Render Output -> Publisher Payload Conformance
  // =========================================================================
  describe('3. Render Output -> Publisher Payload Conformance', () => {
    test('Builds compliant Buffer GraphQL payload for Reel using mock tunnel URL', () => {
      const slot = automator.PRODUCTION_SLOT_BLUEPRINTS[0]; // Reel
      const mockTunnelUrl = 'https://mock-adversarial-tunnel.trycloudflare.com';
      const reelVideoUrl = `${mockTunnelUrl}/sample_reel_1080x1920.mp4`;

      const payload = publisher.buildBufferPostPayload({
        channelId: publisher.TARGET_CHANNEL_ID,
        format: 'reel',
        caption: slot.caption,
        mediaUrls: [reelVideoUrl],
      });

      const validation = publisher.validateBufferPayload(payload);
      assert.strictEqual(validation.valid, true, `Payload validation failed: ${validation.errors.join('; ')}`);
      assert.strictEqual(payload.channelId, '6ad933a2778b240e2f81b45d');
      assert.strictEqual(payload.mode, 'shareNow');
      assert.strictEqual(payload.metadata.instagram.type, 'reel');
      assert.strictEqual(payload.metadata.instagram.shouldShareToFeed, true);
      assert.strictEqual(payload.assets.length, 1);
      assert.strictEqual(payload.assets[0].video.url, reelVideoUrl);
      assert.ok(payload.text.includes('@caleb766h1'), 'Caption must contain founder handle');
      assert.strictEqual(payload.firstComment, undefined, 'No firstComment on free plan');
      assert.strictEqual(payload.metadata.instagram.collaborators, undefined, 'No collaborators in metadata');
    });

    test('Builds compliant Buffer GraphQL payload for Carousel using mock tunnel URL', () => {
      const slot = automator.PRODUCTION_SLOT_BLUEPRINTS[1]; // Carousel
      const mockTunnelUrl = 'https://mock-adversarial-tunnel.trycloudflare.com';
      const slideUrls = [1, 2, 3, 4, 5, 6].map(i => `${mockTunnelUrl}/carousels/slide_${i}.jpg`);

      const payload = publisher.buildBufferPostPayload({
        channelId: publisher.TARGET_CHANNEL_ID,
        format: 'carousel',
        caption: slot.caption,
        mediaUrls: slideUrls,
      });

      const validation = publisher.validateBufferPayload(payload);
      assert.strictEqual(validation.valid, true, `Payload validation failed: ${validation.errors.join('; ')}`);
      assert.strictEqual(payload.channelId, '6ad933a2778b240e2f81b45d');
      assert.strictEqual(payload.mode, 'shareNow');
      assert.strictEqual(payload.metadata.instagram.type, 'carousel');
      assert.strictEqual(payload.metadata.instagram.shouldShareToFeed, true);
      assert.strictEqual(payload.assets.length, 6);
      for (let i = 0; i < 6; i++) {
        assert.strictEqual(payload.assets[i].image.url, slideUrls[i]);
      }
      assert.ok(payload.text.includes('@caleb766h1'), 'Caption must contain founder handle');
      assert.strictEqual(payload.firstComment, undefined);
      assert.strictEqual(payload.metadata.instagram.collaborators, undefined);
    });

    test('Adversarial Publisher Payload: Rejects invalid payloads before dispatch', () => {
      // Missing assets
      const emptyAssetsPayload = {
        channelId: publisher.TARGET_CHANNEL_ID,
        mode: 'shareNow',
        caption: 'Valid caption @caleb766h1',
        metadata: { instagram: { type: 'reel', shouldShareToFeed: true } },
        assets: [],
      };
      assert.strictEqual(publisher.validateBufferPayload(emptyAssetsPayload).valid, false);

      // Wrong mode
      const wrongModePayload = {
        channelId: publisher.TARGET_CHANNEL_ID,
        mode: 'queueLater',
        caption: 'Valid caption @caleb766h1',
        metadata: { instagram: { type: 'reel', shouldShareToFeed: true } },
        assets: [{ video: { url: 'https://example.com/video.mp4' } }],
      };
      assert.strictEqual(publisher.validateBufferPayload(wrongModePayload).valid, false);

      // Wrong channelId
      const wrongChannelPayload = {
        channelId: 'invalid_channel_99999',
        mode: 'shareNow',
        caption: 'Valid caption @caleb766h1',
        metadata: { instagram: { type: 'reel', shouldShareToFeed: true } },
        assets: [{ video: { url: 'https://example.com/video.mp4' } }],
      };
      assert.strictEqual(publisher.validateBufferPayload(wrongChannelPayload).valid, false);
    });
  });

  // =========================================================================
  // 4. Full Pipeline Dry-Run Simulation (Automator -> Guardrails -> Publisher)
  // =========================================================================
  describe('4. Full Pipeline Dry-Run Simulation & Resilience', () => {
    test('Simulating dry-run pipeline verifies complete dataflow with zero mutating operations', async () => {
      let dryRunResult = null;
      let caughtError = null;

      try {
        dryRunResult = await publisher.runDryRun({
          port: 8997,
          caption: 'Di Lira, matcha artisan diseduh fresh dengan pemanis alami stevia tanpa sugar crash. Limited batch order via bio link.\n\nCrafted solo by @caleb766h1',
        });
      } catch (err) {
        caughtError = err;
      }

      if (dryRunResult) {
        // If tunnel provisioned successfully
        assert.strictEqual(dryRunResult.dryRun, true);
        assert.strictEqual(dryRunResult.verified, true);
        assert.strictEqual(dryRunResult.channelId, '6ad933a2778b240e2f81b45d');
        assert.ok(dryRunResult.tunnelUrl.startsWith('https://'));
        assert.ok(dryRunResult.reelPayload.assets.length === 1);
        assert.ok(dryRunResult.carouselPayload.assets.length === 8);
      } else {
        // If Cloudflare public quick tunnel rate-limited (HTTP 429) or timed out
        assert.ok(caughtError, 'Must capture error when dryRunResult is null');
        const isTunnelRateLimitOrTimeout =
          caughtError.message.includes('Cloudflare tunnel startup timed out') ||
          caughtError.message.includes('trycloudflare.com') ||
          caughtError.message.includes('429');

        assert.strictEqual(
          isTunnelRateLimitOrTimeout,
          true,
          `Error must be tunnel timeout/rate-limiting, got: ${caughtError.message}`
        );
      }
    });

    test('Local static HTTP server byte-range and asset mapping verification without external tunnel dependency', async () => {
      const testPort = 8998;
      const sampleReel = path.join(PROJECT_ROOT, 'out/sample_reel_1080x1920.mp4');
      const assetMap = {
        '/media/reel.mp4': sampleReel,
      };

      const server = await publisher.startStaticServer(testPort, assetMap);
      assert.ok(server, 'Static server must start');

      try {
        // Test /health route
        const healthRes = await new Promise((resolve) => {
          const req = require('http').get(`http://127.0.0.1:${testPort}/health`, (res) => {
            let data = '';
            res.on('data', d => data += d);
            res.on('end', () => resolve({ statusCode: res.statusCode, body: data }));
          });
          req.on('error', () => resolve({ statusCode: 500 }));
        });
        assert.strictEqual(healthRes.statusCode, 200);
        assert.strictEqual(healthRes.body, 'OK');

        // Test HTTP 206 Partial Content (Byte Range)
        const rangeRes = await new Promise((resolve) => {
          const req = require('http').get(`http://127.0.0.1:${testPort}/media/reel.mp4`, {
            headers: { 'Range': 'bytes=0-1023' }
          }, (res) => {
            let bytes = 0;
            res.on('data', d => bytes += d.length);
            res.on('end', () => resolve({ statusCode: res.statusCode, bytes, contentRange: res.headers['content-range'] }));
          });
          req.on('error', () => resolve({ statusCode: 500 }));
        });

        assert.strictEqual(rangeRes.statusCode, 206, 'Must return HTTP 206 Partial Content for byte range');
        assert.strictEqual(rangeRes.bytes, 1024, 'Must return exactly 1024 bytes');
        assert.ok(rangeRes.contentRange.startsWith('bytes 0-1023/'), 'Content-Range header must be correct');
      } finally {
        if (server.closeAllConnections) server.closeAllConnections();
        server.close();
      }
    });
  });
});
